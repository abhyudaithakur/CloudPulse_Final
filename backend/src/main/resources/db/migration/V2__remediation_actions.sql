-- CloudPulse schema v2: approved remediations and their outcome (FR-10 to FR-12, NFR-02).

CREATE TABLE remediation_actions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id    BIGINT        NOT NULL REFERENCES incidents (id),
    runbook        VARCHAR(48)   NOT NULL,
    target_service VARCHAR(64)   NOT NULL,
    namespace      VARCHAR(64)   NOT NULL,
    deployment     VARCHAR(64)   NOT NULL,
    approved_by    VARCHAR(64)   NOT NULL,
    approval_note  VARCHAR(500)  NOT NULL,
    status         VARCHAR(16)   NOT NULL CHECK (status IN ('APPROVED', 'EXECUTING', 'ROLLING_OUT',
                                                           'VERIFYING', 'RECOVERED', 'NOT_RECOVERED',
                                                           'FAILED')),
    approved_at    TIMESTAMPTZ   NOT NULL,
    executed_at    TIMESTAMPTZ,
    generation     BIGINT,
    rolled_out_at  TIMESTAMPTZ,
    verify_until   TIMESTAMPTZ,
    finished_at    TIMESTAMPTZ,
    detail         VARCHAR(1000) NOT NULL,
    version        BIGINT        NOT NULL DEFAULT 0
);

-- FR-11 / NFR-02 safety: at most one remediation in progress per incident, even if two approvals
-- race. Enforced by the database, not only by application code.
CREATE UNIQUE INDEX ux_remediation_one_in_progress
    ON remediation_actions (incident_id)
    WHERE status IN ('APPROVED', 'EXECUTING', 'ROLLING_OUT', 'VERIFYING');

CREATE INDEX ix_remediation_incident ON remediation_actions (incident_id, approved_at DESC);
CREATE INDEX ix_remediation_status ON remediation_actions (status);
