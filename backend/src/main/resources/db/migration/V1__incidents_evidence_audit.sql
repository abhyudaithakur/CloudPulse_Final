-- CloudPulse schema v1: incidents, supporting evidence, and an append-only audit trail.

CREATE TABLE incidents (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id            VARCHAR(64)      NOT NULL,
    service_name       VARCHAR(64)      NOT NULL,
    title              VARCHAR(200)     NOT NULL,
    status             VARCHAR(16)      NOT NULL CHECK (status IN ('ACTIVE', 'RESOLVED')),
    severity           VARCHAR(16)      NOT NULL CHECK (severity IN ('MEDIUM', 'HIGH', 'CRITICAL')),
    unit               VARCHAR(16)      NOT NULL,
    comparison         VARCHAR(8)       NOT NULL,
    threshold_value    DOUBLE PRECISION NOT NULL,
    sustain_seconds    BIGINT           NOT NULL,
    recovery_seconds   BIGINT           NOT NULL,
    breach_started_at  TIMESTAMPTZ      NOT NULL,
    opened_at          TIMESTAMPTZ      NOT NULL,
    resolved_at        TIMESTAMPTZ,
    last_value         DOUBLE PRECISION NOT NULL,
    last_observed_at   TIMESTAMPTZ      NOT NULL,
    peak_value         DOUBLE PRECISION NOT NULL,
    last_evidence_at   TIMESTAMPTZ      NOT NULL,
    summary            VARCHAR(1000)    NOT NULL,
    version            BIGINT           NOT NULL DEFAULT 0,
    CONSTRAINT resolved_has_timestamp CHECK ((status = 'RESOLVED') = (resolved_at IS NOT NULL))
);

-- FR-04 enforced by the database: at most one ACTIVE incident per rule and service,
-- even if two detector instances race.
CREATE UNIQUE INDEX ux_incidents_one_active_per_rule_service
    ON incidents (rule_id, service_name)
    WHERE status = 'ACTIVE';

CREATE INDEX ix_incidents_opened_at ON incidents (opened_at DESC);
CREATE INDEX ix_incidents_status ON incidents (status);

CREATE TABLE incident_evidence (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id     BIGINT           NOT NULL REFERENCES incidents (id),
    observed_at     TIMESTAMPTZ      NOT NULL,
    kind            VARCHAR(32)      NOT NULL,
    metric          VARCHAR(64)      NOT NULL,
    observed_value  DOUBLE PRECISION NOT NULL,
    threshold_value DOUBLE PRECISION NOT NULL,
    unit            VARCHAR(16)      NOT NULL,
    source          VARCHAR(32)      NOT NULL,
    promql          VARCHAR(2000)    NOT NULL,
    note            VARCHAR(500)     NOT NULL
);

CREATE INDEX ix_evidence_incident ON incident_evidence (incident_id, observed_at);

CREATE TABLE audit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ   NOT NULL,
    action      VARCHAR(48)   NOT NULL,
    actor       VARCHAR(64)   NOT NULL,
    target      VARCHAR(128)  NOT NULL,
    incident_id BIGINT REFERENCES incidents (id),
    result      VARCHAR(16)   NOT NULL CHECK (result IN ('SUCCESS', 'FAILURE')),
    details     VARCHAR(1000) NOT NULL
);

CREATE INDEX ix_audit_incident ON audit_events (incident_id, occurred_at);
CREATE INDEX ix_audit_occurred_at ON audit_events (occurred_at DESC);

-- NFR-05 / glossary "immutable-style record": the audit trail can only grow.
CREATE FUNCTION reject_audit_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_events is append-only: % is not allowed', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_events_append_only
    BEFORE UPDATE OR DELETE ON audit_events
    FOR EACH ROW EXECUTE FUNCTION reject_audit_mutation();
